    def generate_ropa(
        self,
        org_name: str,
        processing_activities: List[Dict[str, str]],
    ) -> str:
        """
        Generate Records of Processing Activities (RoPA).

        Args:
            org_name: Organization name
            processing_activities: List of dicts with processing activity details

        Returns:
            Path to generated document
        """
        doc = self._create_document("Records of Processing Activities (RoPA)", org_name)

        # Introduction
        self._add_section(
            doc,
            "1. Introduction",
            f"This document contains the {org_name} Records of Processing Activities (RoPA) as "
            "required by DPDPA Section 19. It documents all personal data processing activities "
            "within the organization."
        )

        # Legal Requirement
        self._add_section(
            doc,
            "2. Legal Requirement (Section 19, DPDPA)",
            "Every entity that determines the purposes and means of personal data processing must "
            "maintain records of processing activities. This includes information on: purposes, "
            "categories of Data Principals, data categories, recipients, retention periods, "
            "and security measures."
        )

        # Processing Activities Table
        self._add_section(doc, "3. Processing Activities")

        # Create comprehensive table
        table = doc.add_table(rows=len(processing_activities) + 1, cols=9)
        table.style = 'Light Grid Accent 1'

        # Header row
        headers = [
            "Activity",
            "Purpose",
            "Legal Basis",
            "Data Categories",
            "Data Principals",
            "Recipients",
            "Retention",
            "Security Measures",
            "Cross-border",
        ]
        hdr_cells = table.rows[0].cells
        for idx, header in enumerate(headers):
            hdr_cells[idx].text = header

        # Data rows
        for row_idx, activity in enumerate(processing_activities, 1):
            cells = table.rows[row_idx].cells
            cells[0].text = activity.get("activity", "[Activity Name]")
            cells[1].text = activity.get("purpose", "[Purpose]")
            cells[2].text = activity.get("legal_basis", "[Consent/Legal Obligation/Etc.]")
            cells[3].text = activity.get("data_categories", "[Categories]")
            cells[4].text = activity.get("data_principals", "[Who]")
            cells[5].text = activity.get("recipients", "[Internal/Processors/External]")
            cells[6].text = activity.get("retention", "[Period]")
            cells[7].text = activity.get("security_measures", "[Encryption/Access Control/Etc.]")
            cells[8].text = activity.get("cross_border", "[Yes/No]")

        # Data Subject Rights
        self._add_section(doc, "4. Data Principal Rights")
        doc.add_paragraph(
            "For each processing activity, Data Principals have the following rights:"
        )
        rights = [
            "Right to Access: Obtain a copy of processed data",
            "Right to Correction: Correct inaccurate data",
            "Right to Erasure: Request deletion under specified conditions",
            "Right to Withdraw Consent: Withdraw consent for processing",
            "Right to Grievance Redressal: File complaints for violations",
            "Right to Nominate: Nominate someone to exercise rights posthumously",
        ]
        for right in rights:
            doc.add_paragraph(right, style='List Bullet')

        # Review and Updates
        self._add_section(doc, "5. Review and Updates")
        doc.add_paragraph(
            "This RoPA is reviewed and updated [annually/semi-annually] or whenever processing "
            "activities change. Last reviewed: [DATE]\nNext review: [DATE]"
        )

        # Approval
        doc.add_paragraph()
        approval_para = doc.add_paragraph(
            f"Approved by: ________________ Date: ________________"
        )
        approval_para.paragraph_format.space_before = Pt(12)

        return self._save_document(doc, "Records_of_Processing_Activities.docx")

    def generate_grievance_policy(
        self,
        org_name: str,
        dpo_name: str,
        contact_email: str,
    ) -> str:
        """
        Generate a Grievance Redressal Policy per Section 13, DPDPA.

        Args:
            org_name: Organization name
            dpo_name: Data Protection Officer name
            contact_email: Contact email for grievances

        Returns:
            Path to generated document
        """
        doc = self._create_document("Grievance Redressal Policy", org_name)

        # Preamble
        self._add_section(
            doc,
            "1. Introduction",
            f"{org_name} is committed to addressing the grievances of Data Principals regarding "
            "violations of their rights under the Digital Personal Data Protection Act, 2023 (DPDPA). "
            "This policy outlines the grievance mechanism and timelines for resolution."
        )

        # Legal Framework
        self._add_section(
            doc,
            "2. Legal Framework (Section 13, DPDPA)",
            "Every entity shall implement a mechanism to acknowledge and redress grievances of "
            "Data Principals within the timelines specified by DPDPA Rules."
        )

        # What Constitutes a Grievance
        self._add_section(doc, "3. What Constitutes a Grievance")
        grievances = [
            "Unauthorized processing of personal data",
            "Denial of right to access personal data",
            "Failure to correct inaccurate or incomplete data",
            "Failure to delete personal data upon request",
            "Unauthorized transfer of personal data",
            "Failure to respond to grievance within specified timelines",
            "Any other violation of DPDPA or organizational policies",
        ]
        for grievance in grievances:
            doc.add_paragraph(grievance, style='List Bullet')

        # Filing a Grievance
        self._add_section(doc, "4. How to File a Grievance")

        self._add_subsection(doc, "4.1 Channels for Filing")
        channels = [
            f"Email: {contact_email}",
            "Physical Mail: [Office Address]",
            "Online Form: [Website URL]",
            "In Person: [Office Location]",
        ]
        for channel in channels:
            doc.add_paragraph(channel, style='List Bullet')

        self._add_subsection(doc, "4.2 Information Required")
        doc.add_paragraph("When filing a grievance, please provide:")
        info_required = [
            "Your full name and contact information",
            "Description of the grievance with dates",
            "Relevant personal data or documentation",
            "Action you expect to address the grievance",
            "Any previous communication regarding the grievance",
        ]
        for info in info_required:
            doc.add_paragraph(info, style='List Bullet')

        # Processing Timeline
        self._add_section(doc, "5. Grievance Processing Timeline")

        self._add_subsection(
            doc,
            "5.1 Acknowledgment (Within 48 hours)",
            f"We acknowledge receipt of your grievance within 48 hours. Acknowledgment will include "
            "a reference number, expected resolution timeline, and DPO contact information."
        )

        self._add_subsection(
            doc,
            "5.2 Investigation (Within 90 days)",
            "We investigate the grievance and take necessary corrective actions. You will be updated "
            "on the progress of investigation."
        )

        self._add_subsection(
            doc,
            "5.3 Resolution (Within 90 days)",
            "We provide a detailed response addressing your grievance and actions taken. If the "
            "grievance is rejected, we provide reasons for rejection."
        )

        # Escalation
        self._add_section(doc, "6. Escalation to Data Protection Board")
        doc.add_paragraph(
            "If you are not satisfied with our response, you may escalate your grievance to the "
            "Data Protection Board within 90 days of receipt of our response. Contact details:\n"
            "[Data Protection Board Address]\n"
            "[Phone Number]\n"
            "[Website URL]"
        )

        # No Retaliation
        self._add_section(doc, "7. No Retaliation Policy")
        doc.add_paragraph(
            "We do not retaliate against any Data Principal for filing a grievance in good faith. "
            "Retaliation or harassment will be treated as a serious violation."
        )

        # Data Protection Officer
        self._add_section(doc, "8. Data Protection Officer")
        dpo_info = [
            f"Name: {dpo_name}",
            f"Email: {contact_email}",
            "Phone: [Contact Number]",
            "Office Hours: [Hours]",
        ]
        for info in dpo_info:
            doc.add_paragraph(info, style='List Bullet')

        # Contact Information
        self._add_section(doc, "9. Contact Information")
        contact_details = [
            f"Organization: {org_name}",
            f"Email: {contact_email}",
            "Address: [Office Address]",
            "Phone: [Contact Number]",
            "Website: [Website URL]",
        ]
        for detail in contact_details:
            doc.add_paragraph(detail, style='List Bullet')

        # Policy Review
        self._add_section(doc, "10. Policy Review")
        doc.add_paragraph(
            "This policy is reviewed annually and updated to reflect changes in regulations, "
            "organizational practices, and feedback from Data Principals."
        )

        return self._save_document(doc, "Grievance_Redressal_Policy.docx")

