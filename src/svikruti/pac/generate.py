"""`svikruti init`: bootstrap privacy.yaml from what the code already does.

The generated manifest is in sync with the code by construction. What it
cannot know (purpose, lawful basis, retention, contracts) is written as TODO,
and `svikruti check` reports each TODO until a human fills it in.
"""

from __future__ import annotations

import json
from typing import Dict, List, Optional

from svikruti.models import ScanResult
from svikruti.pac.frameworks import DEFAULT_FRAMEWORKS
from svikruti.pac.reconcile import CodeModel, build_code_model
from svikruti.pac.taxonomy import HIGH_RISK_CATEGORIES, slugify

_CONTAINER_DIRS = {"src", "app", "apps", "services", "service", "packages", "lib", "libs", "internal", "cmd", "pkg", "modules", "backend", "frontend", "server", "client", "api"}
_MAX_ROOT_FILE_ACTIVITIES = 12
_CONFIG_SUFFIXES = {"json", "yml", "yaml", "toml", "ini", "cfg", "conf", "env", "properties", "xml", "example", "sample", "tf", "tfvars"}
CONFIG_GROUP = "configuration"


def _group_key(rel: str) -> str:
    parts = rel.split("/")
    if len(parts) == 1:
        return rel
    dirs = parts[:-1]
    depth = 1
    while depth < len(dirs) and dirs[depth - 1].lower() in _CONTAINER_DIRS:
        depth += 1
    return "/".join(dirs[:depth]) + "/**"


def group_files(model: CodeModel) -> Dict[str, List[str]]:
    groups: Dict[str, List[str]] = {}
    for rel in sorted(model.files):
        groups.setdefault(_group_key(rel), []).append(rel)
    # Root-level config (package.json, .env.example, docker-compose.yml) is one
    # "configuration" activity, not one activity per file.
    config_files = [key for key in groups if "/" not in key and (key.startswith(".") or key.rsplit(".", 1)[-1].lower() in _CONFIG_SUFFIXES)]
    if len(config_files) > 1:
        merged_config: List[str] = []
        for key in config_files:
            merged_config.extend(groups.pop(key))
        groups[CONFIG_GROUP] = sorted(merged_config)
    root_files = [key for key in groups if "/" not in key and key != CONFIG_GROUP]
    if len(root_files) > _MAX_ROOT_FILE_ACTIVITIES:
        merged: List[str] = []
        for key in root_files:
            merged.extend(groups.pop(key))
        groups["*"] = sorted(merged)
    return groups


def _q(value: object) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def _inline(values: List[str]) -> str:
    return "[" + ", ".join(values) + "]"


def generate_manifest(scan: ScanResult, frameworks: Optional[List[str]] = None, organization: str = "TODO") -> str:
    model = build_code_model(scan.evidence, "medium")
    groups = group_files(model)
    processors = {slug: name for facts in model.files.values() for slug, (name, _) in facts.processors.items()}
    processors.update({slug: name for slug, (name, _) in model.website_processors.items()})

    from svikruti.pac.schema import SCHEMA_URL

    lines = [
        f"# yaml-language-server: $schema={SCHEMA_URL}",
        "# privacy.yaml - privacy as code for this repository.",
        "#",
        "# Generated by `svikruti init` from what the code does today. Review it like code:",
        "#   1. Replace every TODO. Code cannot tell you purpose, lawful basis, retention or contracts.",
        "#   2. Merge or rename activities so they match how your business describes its processing.",
        "#   3. Run `svikruti check` in CI. It fails when code and this file drift apart.",
        "#",
        "# Reference: docs/PRIVACY_AS_CODE.md",
        "",
        "version: 1",
        "",
        "organization:",
        f"  name: {_q(organization)}",
        "  role: controller            # controller | processor | both",
        "  privacy_contact: TODO       # published DPO / grievance contact",
        "",
        f"frameworks: {_inline(frameworks or DEFAULT_FRAMEWORKS)}",
        "",
        "policies:",
        "  personal_data_in_logs: deny # deny | warn | allow",
        "  forbidden_categories: []    # categories this codebase must never process",
        "  allowed_transfer_countries: []  # e.g. [IN, EU]; processors elsewhere then need a transfer_mechanism",
        "  ignore_paths: []            # globs excluded from reconciliation (fixtures, vendored samples)",
        "",
        "processing_activities:",
    ]
    used_ids: Dict[str, int] = {}
    if not groups:
        lines[-1] = "processing_activities: []"
    for key, files in groups.items():
        base = slugify(key.replace("/**", "").rsplit(".", 1)[0]) or "application"
        used_ids[base] = used_ids.get(base, 0) + 1
        activity_id = base if used_ids[base] == 1 else f"{base}_{used_ids[base]}"
        categories = sorted({slug for rel in files for slug in model.files[rel].categories})
        logged = sorted({slug for rel in files for slug in model.files[rel].log_categories})
        activity_processors = sorted({slug for rel in files for slug in model.files[rel].processors})
        risky = sorted(set(categories) & HIGH_RISK_CATEGORIES)
        lines += [
            f"  - id: {activity_id}",
            f"    name: {_q(activity_id.replace('_', ' ').title())}",
            "    owner: TODO",
            f"    paths: {_inline([_q(path) for path in (files if key == CONFIG_GROUP else [key])])}",
            f"    data_categories: {_inline(categories)}",
            "    data_subjects: [TODO]     # e.g. customers, employees, patients",
            "    purposes: [TODO]",
            "    legal_basis: TODO         # one value, or per framework: {gdpr: contract, dpdpa: legitimate_use}",
            "    retention: TODO           # e.g. \"7 years after account closure (tax law)\"",
            f"    processors: {_inline(activity_processors)}",
        ]
        if risky:
            lines.append(f"    dpia: TODO                # required: handles {', '.join(risky)}")
        if logged:
            lines.append(f"    # svikruti: {', '.join(logged)} data reaches logs here. Fix the code, or allow with a reason:")
            lines.append(f"    # logging: {{allow: {_inline(logged)}}}")
        lines.append("")
    if lines[-1] != "":
        lines.append("")
    if processors:
        lines.append("processors:")
        flows = model.flows()
        for slug, name in sorted(processors.items()):
            lines += [
                f"  - id: {slug}",
                f"    name: {_q(name)}",
                f"    data_categories: {_inline(sorted(flows.get(slug, [])))}   # what the code passes to this processor",
                "    purpose: TODO",
                "    country: TODO             # ISO country code where the processor handles the data",
                "    contract: TODO            # DPA / contract reference",
                "",
            ]
    else:
        lines += ["processors: []", ""]
    lines += [
        "# Time-boxed, reasoned exceptions. An expired exception re-opens its finding.",
        "exceptions: []",
        "#  - rule: P001",
        "#    activity: checkout",
        "#    category: contact",
        "#    reason: \"Email is logged for fraud investigation; masking ships in Q1.\"",
        "#    approved_by: security-lead",
        "#    expires: 2027-03-31",
        "",
        "# What a repository cannot prove. Each needs an owner and a review date; stale ones stop counting.",
        "attestations: []",
        "#  - obligation: OBL-21",
        "#    statement: \"Rights requests are handled through the support desk within 30 days.\"",
        "#    evidence: https://wiki.example.com/privacy/dsr-runbook",
        "#    owner: privacy-office",
        "#    reviewed: 2026-11-01",
        "",
    ]
    return "\n".join(lines)
